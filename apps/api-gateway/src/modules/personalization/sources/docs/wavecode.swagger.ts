import { applyDecorators } from '@nestjs/common';
import {
  ApiBadRequestResponse,
  ApiBearerAuth,
  ApiConflictResponse,
  ApiForbiddenResponse,
  ApiNotFoundResponse,
  ApiOperation,
  ApiServiceUnavailableResponse,
  ApiUnauthorizedResponse,
} from '@nestjs/swagger';
import { ApiSuccessResponse } from '../../../../common/docs/api-success-response';
import { WavecodeResponseDto } from '../dto/wavecode.dto';

function common(conflict: string, unavailable: string) {
  return [
    ApiBearerAuth(),
    ApiBadRequestResponse({ description: 'Validation failed' }),
    ApiUnauthorizedResponse({ description: 'Missing or invalid credentials' }),
    ApiForbiddenResponse({ description: 'Missing DESIGN_SUBMIT_OWN' }),
    ApiNotFoundResponse({
      description: 'SOURCE_NOT_FOUND (missing, deleted or not yours)',
    }),
    ApiConflictResponse({ description: conflict }),
    ApiServiceUnavailableResponse({ description: unavailable }),
    ApiSuccessResponse({
      type: WavecodeResponseDto,
      description: 'WAVECODE style state',
    }),
  ];
}

const PREVIEWS =
  'Preview URLs are presigned, valid for 300 s and sent with Cache-Control: no-store; never log or cache them. No object keys or checksums are returned.';

export function ApiResegmentSoundwaveDocs() {
  return applyDecorators(
    ApiOperation({
      summary: '[PERSO-035] Pick another 3 s segment of the uploaded audio',
      description: `Requires Bearer auth and permission DESIGN_SUBMIT_OWN. Allowed for a SOUNDWAVE source that is READY or PROCESSING_FAILED and has no accepted style, at most 10 times. The old results are deleted, the source returns to ACCEPTED and is processed again (poll PERSO-012 or PERSO-032). Optional wavecodeStyle replaces the current style. ${PREVIEWS}`,
    }),
    ...common(
      'SOURCE_BUSY (ACCEPTED or PROCESSING), WAVECODE_STYLE_LOCKED (a style was accepted), SOURCE_NOT_READY, or RESEGMENT_LIMIT_REACHED',
      'Operations or object storage is unavailable',
    ),
  );
}

export function ApiGetWavecodeDocs() {
  return applyDecorators(
    ApiOperation({
      summary:
        '[PERSO-032] Read a Soundwave source: status, segment and WAVECODE styles',
      description: `Requires Bearer auth and permission DESIGN_SUBMIT_OWN. Works for every non-deleted SOUNDWAVE source of the caller, so the customer can resume: status, failureCode, durationMs, segmentStartMs, segmentDurationMs, rawAudioUrl and segmentAudioUrl (READY only), plus the three styles with generated true/false (true only while READY) and preview URLs. Read only: the worker is not called. ${PREVIEWS}`,
    }),
    ...common(
      'SOURCE_NOT_READY: the source is not a SOUNDWAVE',
      'Operations or object storage is unavailable',
    ),
  );
}

export function ApiSelectWavecodeStyleDocs() {
  return applyDecorators(
    ApiOperation({
      summary: '[PERSO-033] Switch the current WAVECODE style',
      description: `Requires Bearer auth and permission DESIGN_SUBMIT_OWN. A style that was generated before is reused; otherwise it is generated by the processing worker (this can take a few seconds). Returns the updated state. ${PREVIEWS}`,
    }),
    ...common(
      'SOURCE_NOT_READY, or WAVECODE_STYLE_LOCKED after a style was accepted (PERSO-034)',
      'PROCESSING_WORKER_UNAVAILABLE when a style must be generated and the worker is down; Operations or object storage unavailable',
    ),
  );
}

export function ApiAcceptWavecodeStyleDocs() {
  return applyDecorators(
    ApiOperation({
      summary: '[PERSO-034] Accept one WAVECODE style and delete the others',
      description: `Requires Bearer auth and permission DESIGN_SUBMIT_OWN. Body style is optional (default: the current style); it is generated first if needed. After acceptance the choice is locked and the other styles are deleted. Idempotent. If deleting the other styles fails after the acceptance was saved, the call still answers 200 and the cleanup is retried the next time accept is called with the same style. Accepting a style does not replace the customer design approval (PERSO-018). ${PREVIEWS}`,
    }),
    ...common(
      'SOURCE_NOT_READY, or WAVECODE_STYLE_LOCKED when a different style was already accepted',
      'PROCESSING_WORKER_UNAVAILABLE when the style must be generated and the worker is down; Operations or object storage unavailable',
    ),
  );
}
